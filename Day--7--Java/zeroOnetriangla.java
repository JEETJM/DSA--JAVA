import java.util.Scanner;

public class zeroOnetriangla {
    public static void zeroOneTrain(int n) {
        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= i; j++) {
                if ((i + j) % 2 == 0) {
                    System.out.print("1 ");
                } else {
                    System.out.print("0 ");
                }
            }
            System.out.println();
        }
    }

    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        System.out.print("Enter number: ");
        int store = sc.nextInt();
        zeroOneTrain(store);
        sc.close();
    }
}